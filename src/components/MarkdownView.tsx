/**
 * Normalizes mathematical formulas generated by LLMs:
 * 1. Converts LaTeX block math delimiters \[ ... \] to display math $$ ... $$.
 * 2. Converts LaTeX inline math delimiters \( ... \) to inline math $ ... $.
 * 3. Expands single-line display math "$$ ... $$" to multi-line "$$\n...\n$$" for proper display block rendering.
 * 4. Ensures display math blocks ($$) have preceding/following blank lines for CommonMark block parsing.
 * 5. Leaves code blocks (fenced ``` and inline `) completely untouched.
 */
function preprocessMath(raw: string): string {
  if (!raw) return '';
  // Split by code blocks or inline code to preserve code untouched
  const segments = raw.split(/(```[\s\S]*?```|`[^`\n]+`)/g);

  return segments
    .map((segment, index) => {
      // Odd indices are code segments
      if (index % 2 === 1) return segment;

      let s = segment;

      // 1. LaTeX display math \[ ... \] -> $$ ... $$
      s = s.replace(/\\\[([\s\S]*?)\\\]/g, (_, math) => `\n\n$$\n${math.trim()}\n$$\n\n`);

      // 2. LaTeX inline math \( ... \) -> $ ... $
      s = s.replace(/\\\(([\s\S]*?)\\\)/g, (_, math) => `$${math.trim()}$`);

      // 3. Single-line display math "$$ ... $$" -> multi-line "$$\n...\n$$"
      s = s.replace(/^\s*\$\$\s*([^\$\n]+?)\s*\$\$\s*$/gm, (_, math) => `\n\n$$\n${math.trim()}\n$$\n\n`);

      // 4. Ensure $$ blocks have empty lines before and after if preceded/followed by regular text
      s = s.replace(/([^\n])\n(\$\$[\s\S]*?\$\$)/g, '$1\n\n$2');
      s = s.replace(/(\$\$[\s\S]*?\$\$)\n([^\n])/g, '$1\n\n$2');

      return s;
    })
    .join('');
}

/**
 * Preprocesses markdown to fix common LLM formatting inconsistencies:
 * 1. Normalizes math equations (display and inline LaTeX).
 * 2. Normalizes CRLF (\r\n) to LF (\n).
 * 3. Removes accidental blank lines inside tables (e.g. between header, delimiter, or rows).
 * 4. Ensures tables without an explicit delimiter row get an automatic GFM delimiter row.
 * 5. Ensures there is a preceding blank line before a table if preceded by regular text.
 * 6. Safely skips fenced code blocks so code contents remain intact.
 */
function preprocessMarkdown(content: string): string {
  if (!content) return '';

  const noThinking = stripThinking(content);
  const mathNormalized = preprocessMath(noThinking);
  const text = mathNormalized.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = text.split('\n');
  const result: string[] = [];

  let inCodeBlock = false;
  let inTable = false;

  function isTableRow(line: string): boolean {
    const trimmed = line.trim();
    if (!trimmed.includes('|')) return false;
    if (trimmed.startsWith('|')) return true;
    if (/^:?-+:?\s*\|/.test(trimmed)) return true;
    const pipeCount = (trimmed.match(/\|/g) || []).length;
    return pipeCount >= 1;
  }

  function isDelimiterRow(line: string): boolean {
    const trimmed = line.trim();
    if (!trimmed.includes('|')) return false;
    // Delimiter row consists of |, -, :, and spaces
    return /^\|?(\s*:?-+:?\s*\|)+\s*:?-+:?\s*\|?$/.test(trimmed);
  }

  function countColumns(line: string): number {
    const trimmed = line.trim();
    const cells = trimmed.split('|');
    if (trimmed.startsWith('|')) cells.shift();
    if (trimmed.endsWith('|')) cells.pop();
    return Math.max(cells.length, 1);
  }

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    // Toggle fenced code blocks
    if (trimmed.startsWith('```')) {
      inCodeBlock = !inCodeBlock;
      inTable = false;
      result.push(line);
      continue;
    }

    if (inCodeBlock) {
      result.push(line);
      continue;
    }

    if (trimmed === '') {
      if (inTable) {
        // Look ahead for next non-empty line
        let nextNonEmptyIndex = -1;
        for (let j = i + 1; j < lines.length; j++) {
          if (lines[j].trim() !== '') {
            nextNonEmptyIndex = j;
            break;
          }
        }
        if (nextNonEmptyIndex !== -1 && isTableRow(lines[nextNonEmptyIndex])) {
          // Skip blank line inside table
          continue;
        } else {
          inTable = false;
          result.push(line);
        }
      } else {
        result.push(line);
      }
    } else if (isTableRow(line)) {
      if (!inTable) {
        // Table started: ensure preceding blank line if previous line is non-empty text
        if (result.length > 0 && result[result.length - 1].trim() !== '') {
          result.push('');
        }
        inTable = true;
        result.push(line);

        // Check if next row exists and if delimiter row is missing
        let nextNonEmptyIndex = -1;
        for (let j = i + 1; j < lines.length; j++) {
          if (lines[j].trim() !== '') {
            nextNonEmptyIndex = j;
            break;
          }
        }
        if (nextNonEmptyIndex !== -1 && isTableRow(lines[nextNonEmptyIndex])) {
          const nextLine = lines[nextNonEmptyIndex];
          if (!isDelimiterRow(nextLine)) {
            const cols = Math.max(countColumns(line), countColumns(nextLine));
            const delimiter = '| ' + Array(cols).fill('---').join(' | ') + ' |';
            result.push(delimiter);
          }
        }
      } else {
        result.push(line);
      }
    } else {
      inTable = false;
      result.push(line);
    }
  }

  return result.join('\n');
}

/* ── Component ───────────────────────────────────────────────────── */
export const MarkdownView: React.FC<MarkdownViewProps> = ({ content }) => {
  const processedContent = useMemo(() => preprocessMarkdown(content), [content]);

  const components: Components = {
    /* ── Headings ─────────────────────────────────────────────── */
    h1: ({ children }) => <h1 style={s.h1}>{children}</h1>,
    h2: ({ children }) => <h2 style={s.h2}>{children}</h2>,
    h3: ({ children }) => <h3 style={s.h3}>{children}</h3>,
    h4: ({ children }) => <h4 style={s.h4}>{children}</h4>,

    /* ── Paragraph ────────────────────────────────────────────── */
    p: ({ children }) => <p style={s.paragraph}>{children}</p>,

    /* ── Inline formatting ────────────────────────────────────── */
    strong: ({ children }) => <strong style={s.strong}>{children}</strong>,
    em: ({ children }) => <em style={s.em}>{children}</em>,
    del: ({ children }) => <del style={s.del}>{children}</del>,

    /* ── Links ────────────────────────────────────────────────── */
    a: ({ href, children }) => (
      <a href={href} target="_blank" rel="noopener noreferrer" style={s.link}>
        {children}
      </a>
    ),

    /* ── Lists ────────────────────────────────────────────────── */
    ul: ({ children }) => <ul style={s.ul}>{children}</ul>,
    ol: ({ children }) => <ol style={s.ol}>{children}</ol>,
    li: ({ children }) => <li style={s.li}>{children}</li>,

    /* ── Blockquote ───────────────────────────────────────────── */
    blockquote: ({ children }) => (
      <blockquote style={s.blockquote}>{children}</blockquote>
    ),

    /* ── Horizontal rule ─────────────────────────────────────── */
    hr: () => <hr style={s.hr} />,

    /* ── Code (inline + fenced blocks) ────────────────────────── */
    code: ({ node, className, children, ...props }: any) => {
      const match = /language-(\w+)/.exec(className || '');
      const language = match ? match[1] : '';
      const codeString = String(children).replace(/\n$/, '');

      // Detect fenced code blocks (multi-line or has language class)
      const isBlock =
        (node?.position?.start?.line !== node?.position?.end?.line) ||
        className?.startsWith('language-');

      if (isBlock || className) {
        return (
          <div style={s.codeBlock}>
            <div style={s.codeBlockHeader}>
              <span style={s.codeBlockLang}>{language || 'code'}</span>
              <CopyButton code={codeString} />
            </div>
            <SyntaxHighlighter
              style={radTheme as any}
              language={language || 'text'}
              PreTag="div"
              customStyle={s.syntaxPre}
              codeTagProps={{
                style: {
                  fontFamily:
                    'var(--font-mono, "JetBrains Mono", "Fira Code", monospace)',
                },
              }}
            >
              {codeString}
            </SyntaxHighlighter>
          </div>
        );
      }

      // Inline code
      return (
        <code style={s.inlineCode} {...props}>
          {children}
        </code>
      );
    },

    /* ── Tables (GFM) ─────────────────────────────────────────── */
    table: ({ children, ...props }: any) => (
      <div className="rad-markdown-table-wrapper" style={s.tableWrapper}>
        <table className="rad-markdown-table" style={s.table} {...props}>
          {children}
        </table>
      </div>
    ),
    thead: ({ children, ...props }: any) => (
      <thead style={s.thead} {...props}>
        {children}
      </thead>
    ),
    tbody: ({ children, ...props }: any) => <tbody {...props}>{children}</tbody>,
    tr: ({ children, ...props }: any) => (
      <tr style={s.tr} {...props}>
        {children}
      </tr>
    ),
    th: ({ children, style, ...props }: any) => (
      <th style={{ ...s.th, ...style }} {...props}>
        {children}
      </th>
    ),
    td: ({ children, style, ...props }: any) => (
      <td style={{ ...s.td, ...style }} {...props}>
        {children}
      </td>
    ),
  };

  return (
    <div style={s.container}>
      <ReactMarkdown
        remarkPlugins={[remarkGfm, remarkMath]}
        rehypePlugins={[[rehypeKatex, { throwOnError: false, strict: false }]]}
        components={components}
      >
        {processedContent}
      </ReactMarkdown>
    </div>
  );
};

